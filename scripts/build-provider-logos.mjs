#!/usr/bin/env node
// Builds src/lib/providerLogos.ts from the simple-icons package (CC0), keeping only the glyphs that
// src/lib/providers.ts references via `logo: "<slug>"`:
//   npm pack simple-icons && tar xzf simple-icons-*.tgz
//   node scripts/build-provider-logos.mjs path/to/package
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/build-provider-logos.mjs <simple-icons package dir>");
  process.exit(1);
}
const pkg = JSON.parse(readFileSync(join(source, "package.json"), "utf8"));
const data = JSON.parse(readFileSync(join(source, "data/simple-icons.json"), "utf8"));
const icons = Array.isArray(data) ? data : data.icons;
const registry = readFileSync(new URL("../src/lib/providers.ts", import.meta.url), "utf8");
const slugs = [...new Set([...registry.matchAll(/logo: "([a-z0-9]+)"/g)].map((m) => m[1]))].sort();

const out = {};
for (const slug of slugs) {
  const icon = icons.find((i) => i.slug === slug);
  if (!icon) {
    console.error(`missing icon: ${slug}`);
    process.exit(1);
  }
  const svg = readFileSync(join(source, "icons", `${slug}.svg`), "utf8");
  const path = svg.match(/<path d="([^"]+)"/)?.[1];
  if (!path) {
    console.error(`no path in ${slug}.svg`);
    process.exit(1);
  }
  out[slug] = { title: icon.title, hex: icon.hex, path };
}

const body = Object.entries(out)
  .map(([slug, v]) => `  ${slug}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  new URL("../src/lib/providerLogos.ts", import.meta.url),
  `// Generated by scripts/build-provider-logos.mjs from simple-icons ${pkg.version} (CC0 1.0,
// https://simpleicons.org). Do not edit by hand. The brands shown are trademarks of their owners and
// are used only to identify the provider of a booking.

export const LOGOS: Record<string, { title: string; hex: string; path: string }> = {
${body}
};
`,
);
console.log(`${slugs.length} logos written`);
